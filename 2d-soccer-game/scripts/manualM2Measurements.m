function n=manualM2Measurements()
%MANUALM2MEASUREMENTS Recompute documented values from real recorded inputs.
root=tdpSetup();cd(root);
[code,txt]=system('python3 scripts/analyze_webots.py evidence/5/closed-02');assert(code==0,txt);a=jsondecode(txt);
s=jsondecode(fileread('evidence/4/ros-01/receipt.json'));
m=jsondecode(fileread('evidence/5/motion-02/webots-receipt.json'));
c=jsondecode(fileread('evidence/5/closed-02/camera-ros.json'));
f=fopen('evidence/5/closed-02/camera-ros.bgra','rb');cleanup=onCleanup(@()fclose(f));bytes=fread(f,inf,'*uint8');
[rgb,e]=DecodeBgra(bytes,c.width,c.height,c.step,uint8(strcmp(c.encoding,'bgra8')));
assert(e==0);assert(numel(unique(rgb(:)))>10);
raw=jsondecode(fileread('evidence/5/closed-02/proxy-records.json'));frames=zeros(numel(raw),20);
for k=1:numel(raw),frames(k,:)=reshape(raw(k).frame,1,20);end
P=tdp.defaultConfig();P.dt=.04;P.mode=TdpMode.Delayed;cfg=jsondecode(fileread('config/webots.json'));
P.kickTimeout=cfg.kickTimeoutSeconds;P.recoverTime=cfg.recoverTimeSeconds;
actual=runFrameReplay(P,frames);saved=jsondecode(fileread('evidence/5/closed-02/matlab-actions.json'));assert(isequal(actual,saved));
n=struct('scalarInput',s.scalar.input,'scalarOutput',s.scalar.output,'rosReplayFrames',s.frames, ...
 'webotsFrames',a.frames,'clockPublishers',a.clockPublishers,'initialDistanceMetres',a.initialDistanceMetres, ...
 'distanceAtShootMetres',a.distanceAtShootMetres,'requestId',a.requestId,'motionStartSeconds',a.motionStartSeconds, ...
 'motionEndSeconds',a.motionEndSeconds,'motionDurationSeconds',a.motionDurationSeconds, ...
 'motionEventBallDisplacementMetres',a.motionEventBallDisplacementMetres,'sampledBallDisplacementMetres',a.ballDisplacementMetres, ...
 'ballEvaluationTimeSeconds',a.ballEvaluationTimeSeconds,'sampledBallPeakSpeedMetresPerSecond',a.ballPeakSpeedMetresPerSecond, ...
 'duplicateDeliveries',a.extraDuplicateDeliveries,'physicalExecutions',a.physicalExecutions, ...
 'motionOnlyBallDisplacementMetres',m.kickResults.ballDisplacementAtMotionEnd, ...
 'cameraErrorCode',double(e),'cameraWidth',c.width,'cameraHeight',c.height,'cameraBytes',c.bytes);
end
