function P = validateV1Config(P)
%VALIDATEV1CONFIG Check tactical geometry and fixed-size fault schedules.
tdp.validateConfig(P);
assert(islogical(P.v1Enabled) && isscalar(P.v1Enabled) && P.v1Enabled, ...
    'TDP:V1Config','Enable the V1 tactics profile explicitly.');
assert(P.mode==TdpMode.Delayed,'TDP:V1Mode', ...
    'V1 requires the delayed skill-stage executor for search and feedback.');
positive = {'v1MidlineBand','v1SupportTrail','v1SupportWidth','v1LooseRange', ...
    'v1LooseSpeed','v1OpponentClearance','v1KeeperInset','v1ScreenDepth', ...
    'v1CounterDepth'};
for k = 1:numel(positive)
    value = P.(positive{k});
    assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
        isfinite(value) && value>0,'TDP:V1Config','Invalid %s.',positive{k});
end
assert(P.v1MidlineBand < P.L/2 && P.v1SupportTrail < P.L && ...
    P.v1SupportWidth < P.W && P.v1KeeperInset < P.goalAreaL && ...
    P.v1KeeperInset >= P.robotR && P.v1ScreenDepth < P.L/2 && ...
    P.v1CounterDepth < P.L/2,'TDP:V1Config','Tactical target outside pitch geometry.');
if isfield(P,'v1AutoRecoveryTeams')
    assert(isfield(P,'v1AutoRecovery') && isequal(P.v1AutoRecovery,true) && ...
        islogical(P.v1AutoRecoveryTeams) && isequal(size(P.v1AutoRecoveryTeams),[1 2]), ...
        'TDP:TeamRecoveryMask','Use a 1-by-2 logical row [blue red] with recovery enabled.');
end
if isfield(P,'v1AutoRecovery')
    assert(islogical(P.v1AutoRecovery) && isscalar(P.v1AutoRecovery), ...
        'TDP:RecoveryConfig','v1AutoRecovery must be a scalar logical.');
    if P.v1AutoRecovery
        assert(isfield(P,'v1RecoveryHealthySeconds') && isfield(P,'v1HealthDropWindow'), ...
            'TDP:RecoveryConfig','Use tdp.recoveryConfig to supply the experimental settings.');
        duration=P.v1RecoveryHealthySeconds;
        assert(isnumeric(duration) && isreal(duration) && isscalar(duration) && ...
            isfinite(duration) && duration>0,'TDP:RecoveryConfig','The healthy interval must be positive.');
    end
end
if isfield(P,'v11Fallback')
    assert(islogical(P.v11Fallback) && isscalar(P.v11Fallback), ...
        'TDP:V11Config','v11Fallback must be a scalar logical.');
    assert(~(isfield(P,'v1AutoRecovery') && P.v1AutoRecovery), ...
        'TDP:V11Config','The V1.1 fallback runs only in the approved V1 model.');
    count=P.v11FailCount;
    assert(isnumeric(count) && isscalar(count) && count==round(count) && ...
        count>=1 && count<=8,'TDP:V11Config','v11FailCount must be an integer in 1..8.');
    seconds={'v11FailWindow','v11RecoverSeconds'};
    for k=1:numel(seconds)
        value=P.(seconds{k});
        assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
            isfinite(value) && value>0,'TDP:V11Config','Invalid %s.',seconds{k});
    end
end
names = {'v1UnavailableWindow','v1BlindWindow','v1StaleWindow', ...
    'v1StopWindow','v1RecoveryWindow','v1FailWindow'};
counts = [8 8 8 1 2 8];
if isfield(P,'v1AutoRecovery') && P.v1AutoRecovery
    names{end+1}='v1HealthDropWindow';
    counts(end+1)=8;
end
for k = 1:numel(names)
    window = P.(names{k});
    assert(isnumeric(window) && isreal(window) && isequal(size(window),[counts(k) 2]) && ...
        all(isfinite(window(:))) && all(window(:,1)>=0) && ...
        all(window(:,2)>=window(:,1)),'TDP:V1Window','Invalid %s.',names{k});
end
end
