#!/usr/bin/env python3
"""Generate the ENG5325 TDP Webots world: protos/TdpPitch.proto, protos/TdpBall.proto and worlds/pitch.wbt.

Webots PROTO templates only support JavaScript, so all geometry is computed here in Python
and written out as plain PROTO files. Edit the parameters below, then run:

    python3 generate_world.py
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent

# TDP KidSize pitch, dimensions from Table 1 of the ENG5325 specification,
# details not given there (line width, goal posts, nets) from the RoboCup Humanoid League 2025 rules, Law 1.
# Origin at the centre spot, x along the length, y across, z up.
# Area dimensions are measured to the outer edge of the lines (lines belong to the areas they bound).
# The goal posts stand on the goal line, so the penalty mark is measured from the centre of the goal line.
LENGTH = 9                    # A
WIDTH = 6                     # B
GOAL_DEPTH = 0.6              # C
GOAL_WIDTH = 2.6              # D, between the inside of the posts
GOAL_HEIGHT = 1.2             # ground to the lower edge of the crossbar
GOAL_AREA_LENGTH = 1          # E
GOAL_AREA_WIDTH = 3           # F
PENALTY_MARK_DISTANCE = 1.5   # G
CENTRE_CIRCLE_DIAMETER = 1.5  # H
BORDER_WIDTH = 1              # I
PENALTY_AREA_LENGTH = 2       # J
PENALTY_AREA_WIDTH = 5        # K
LINE_WIDTH = 0.05             # RoboCup: about 5 cm
GOAL_POST_DIAMETER = 0.1      # RoboCup: 8 to 12 cm, white
MARK = 0.1                    # size of the penalty and centre crosses
NET = 0.01                    # thickness of the net panels
CIRCLE_SEGMENTS = 48

# TDP match ball: similar to a FIFA size 1 ball, 45 cm circumference (radius 0.45 / 2 pi = 0.0716 m),
# bright orange as allowed by the ENG5325 specification.
# The mass is not given in the specification: weigh the real ball and update BALL_MASS.
# The ball is a thin hollow shell, so its moment of inertia is 2/3 m r^2 (a solid sphere would be 2/5 m r^2).
# Damping stands in for rolling resistance on grass, which the physics engine does not model.
BALL_RADIUS = 0.0716
BALL_MASS = 0.2
BALL_COLOR = (1, 0.4, 0)
BALL_DAMPING = 0.2

# grass/ball contact
FRICTION = 0.5
BOUNCE = 0.5
BOUNCE_VELOCITY = 0.05

HEADER = "#VRML_SIM R2025a utf8\n# Generated by generate_world.py: edit the parameters there, not this file.\n"
WHITE = "PBRAppearance { baseColor 1 1 1 roughness 1 metalness 0 }"
POST = "PBRAppearance { baseColor 1 1 1 roughness 0.4 metalness 0 }"
NET_APPEARANCE = "PBRAppearance { baseColor 0.15 0.15 0.15 transparency 0.6 roughness 1 metalness 0 }"
UPRIGHT = "0 0 1 0"


def f(*values):
    """Format numbers for VRML, without float noise such as 0.30000000000000004."""
    out = []
    for v in values:
        s = f"{v:.6f}".rstrip("0").rstrip(".")
        out.append("0" if s in ("", "-0") else s)
    return " ".join(out)


def indent(text, n):
    return "\n".join(" " * n + line if line else line for line in text.splitlines())


def line_boxes():
    """Every line is a thin white box: (x, y, size along x, size along y, rotation about z)."""
    L, W, w = LENGTH, WIDTH, LINE_WIDTH
    boxes = [
        (0, W / 2 - w / 2, L, w, 0),     # touchlines
        (0, -W / 2 + w / 2, L, w, 0),
        (0, 0, w, W, 0),                 # halfway line
        (0, 0, MARK, w, 0),              # centre mark
    ]
    for s in (-1, 1):
        boxes.append((s * (L / 2 - w / 2), 0, w, W, 0))  # goal line
        for d, b in ((GOAL_AREA_LENGTH, GOAL_AREA_WIDTH), (PENALTY_AREA_LENGTH, PENALTY_AREA_WIDTH)):
            boxes.append((s * (L / 2 - d + w / 2), 0, w, b, 0))
            boxes.append((s * (L / 2 - d / 2), b / 2 - w / 2, d, w, 0))
            boxes.append((s * (L / 2 - d / 2), -b / 2 + w / 2, d, w, 0))
        px = s * (L / 2 - w / 2 - PENALTY_MARK_DISTANCE)  # penalty mark (a cross)
        boxes.append((px, 0, MARK, w, 0))
        boxes.append((px, 0, w, MARK, 0))
    rc = CENTRE_CIRCLE_DIAMETER / 2 - w / 2  # centre circle from short segments
    t = 2 * rc * math.tan(math.pi / CIRCLE_SEGMENTS)
    for i in range(CIRCLE_SEGMENTS):
        a = 2 * math.pi * i / CIRCLE_SEGMENTS
        boxes.append((rc * math.cos(a), rc * math.sin(a), w, t, a))
    return boxes


def goal_parts(s):
    """Goal parts: (x, y, z, rotation, geometry, appearance); the posts are centred on the goal line."""
    r = GOAL_POST_DIAMETER / 2
    D, Hg = GOAL_WIDTH, GOAL_HEIGHT
    x0 = LENGTH / 2 - LINE_WIDTH / 2  # post centres, on the goal line
    x1 = LENGTH / 2 + GOAL_DEPTH      # back of the net
    top = Hg + 2 * r
    zc, xm = top / 2, s * (x0 + x1) / 2
    post = f"Cylinder {{ radius {f(r)} height {f(top)} }}"
    return [
        (s * x0, D / 2 + r, zc, UPRIGHT, post, POST),
        (s * x0, -D / 2 - r, zc, UPRIGHT, post, POST),
        (s * x0, 0, Hg + r, "1 0 0 1.5708", f"Cylinder {{ radius {f(r)} height {f(D + 4 * r)} }}", POST),
        (s * (x1 - NET / 2), 0, zc, UPRIGHT, f"Box {{ size {f(NET, D + 2 * r, top)} }}", NET_APPEARANCE),
        (xm, D / 2 + r, zc, UPRIGHT, f"Box {{ size {f(x1 - x0, NET, top)} }}", NET_APPEARANCE),
        (xm, -D / 2 - r, zc, UPRIGHT, f"Box {{ size {f(x1 - x0, NET, top)} }}", NET_APPEARANCE),
        (xm, 0, top - NET / 2, UPRIGHT, f"Box {{ size {f(x1 - x0, D + 2 * r, NET)} }}", NET_APPEARANCE),
    ]


def goal_solid(s):
    parts = goal_parts(s)
    shapes = "\n".join(
        f"Pose {{\n  translation {f(x, y, z)}\n  rotation {rot}\n"
        f"  children [ Shape {{ appearance {app} geometry {geo} }} ]\n}}"
        for x, y, z, rot, geo, app in parts
    )
    bounds = "\n".join(
        f"Pose {{\n  translation {f(x, y, z)}\n  rotation {rot}\n  children [ {geo} ]\n}}"
        for x, y, z, rot, geo, _ in parts
    )
    name = "goal_left" if s < 0 else "goal_right"
    return (
        f'Solid {{\n  name "{name}"\n  children [\n{indent(shapes, 4)}\n  ]\n'
        f"  boundingObject Group {{\n    children [\n{indent(bounds, 6)}\n    ]\n  }}\n}}"
    )


def pitch_proto():
    lines = "\n".join(
        f"Pose {{\n  translation {f(x, y, 0.001)}\n  rotation 0 0 1 {f(a)}\n"
        f"  children [ Shape {{ appearance {WHITE} geometry Box {{ size {f(sx, sy, 0.002)} }} }} ]\n}}"
        for x, y, sx, sy, a in line_boxes()
    )
    goals = "\n".join(goal_solid(s) for s in (-1, 1))
    carpet = f(LENGTH + 2 * BORDER_WIDTH, WIDTH + 2 * BORDER_WIDTH)
    return f"""{HEADER}
PROTO TdpPitch [
]
{{
  Solid {{
    name "pitch"
    children [
      Shape {{
        appearance PBRAppearance {{ baseColor 0.1 0.5 0.1 roughness 1 metalness 0 }}
        geometry DEF CARPET Plane {{ size {carpet} }}
      }}
{indent(lines, 6)}
{indent(goals, 6)}
    ]
    boundingObject USE CARPET
    contactMaterial "grass"
  }}
}}
"""


def ball_proto():
    # radius and mass are baked in here because the inertia depends on them
    inertia = 2 / 3 * BALL_MASS * BALL_RADIUS ** 2
    return f"""{HEADER}
PROTO TdpBall [
  field SFVec3f    translation 0 0 {f(BALL_RADIUS)}
  field SFRotation rotation    0 0 1 0
  field SFString   name        "ball"
  field SFColor    color       {f(*BALL_COLOR)}
  field SFFloat    damping     {f(BALL_DAMPING)}
]
{{
  Solid {{
    translation IS translation
    rotation IS rotation
    name IS name
    children [
      Shape {{
        appearance PBRAppearance {{ baseColor IS color roughness 0.6 metalness 0 }}
        geometry DEF BALL_SPHERE Sphere {{ radius {f(BALL_RADIUS)} subdivision 4 }}
      }}
    ]
    boundingObject USE BALL_SPHERE
    contactMaterial "ball"
    physics Physics {{
      density -1
      mass {f(BALL_MASS)}
      centerOfMass [ 0 0 0 ]
      inertiaMatrix [ {f(inertia, inertia, inertia)} 0 0 0 ]
      damping Damping {{ linear IS damping angular IS damping }}
    }}
  }}
}}
"""


def world():
    return f"""{HEADER}
EXTERNPROTO "../protos/TdpPitch.proto"
EXTERNPROTO "../protos/TdpBall.proto"

WorldInfo {{
  info [
    "ENG5325 TDP: KidSize pitch, {f(LENGTH)} m x {f(WIDTH)} m with a {f(BORDER_WIDTH)} m border strip, FIFA size 1 ball"
  ]
  title "TDP pitch"
  basicTimeStep 8
  contactProperties [
    ContactProperties {{
      material1 "grass"
      material2 "ball"
      coulombFriction [ {f(FRICTION)} ]
      bounce {f(BOUNCE)}
      bounceVelocity {f(BOUNCE_VELOCITY)}
    }}
  ]
}}
Viewpoint {{
  orientation -0.2879 0.2879 0.9134 1.6612
  position 0 -13 9
}}
Background {{
  skyColor [ 0.55 0.7 0.9 ]
}}
DirectionalLight {{
  direction -0.3 0.5 -1
  intensity 2
}}
DEF PITCH TdpPitch {{
}}
DEF BALL TdpBall {{
}}
"""


def main():
    outputs = {
        ROOT / "protos" / "TdpPitch.proto": pitch_proto(),
        ROOT / "protos" / "TdpBall.proto": ball_proto(),
        ROOT / "worlds" / "pitch.wbt": world(),
    }
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
